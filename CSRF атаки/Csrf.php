<?php
// Файл: Csrf.php
// Назначение: защита от CSRF-атак с использованием синхронного токена в сессии

session_start(); // Запуск сессии для хранения токена

class Csrf {

    /**
     * Метод token()
     * Что делает: генерирует или возвращает существующий CSRF-токен
     * Почему так: 
     *   - Токен хранится в сессии (не в БД) для производительности
     *   - random_bytes(32) обеспечивает криптостойкую случайность
     *   - bin2hex() преобразует бинарные данные в читаемый вид
     *   - Проверка empty() нужна, чтобы не перезаписывать существующий токен
     */
    public static function token(): string {
        if (empty($_SESSION['csrf_token'])) {
            $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
        }
        return $_SESSION['csrf_token'];
    }

    /**
     * Метод check()
     * Что делает: проверяет переданный токен из запроса
     * Почему так:
     *   - hash_equals() используется вместо == для защиты от timing-атак
     *     (сравнение выполняется за фиксированное время)
     *   - Проверка !empty() нужна, чтобы избежать ошибки при отсутствии токена
     *   - Возвращает false, если токен не совпадает или отсутствует
     */
    public static function check(string $token): bool {
        return !empty($_SESSION['csrf_token']) &&
               hash_equals($_SESSION['csrf_token'], $token);
    }

    /**
     * Метод field()
     * Что делает: вставляет скрытое поле с токеном в HTML-форму
     * Почему так:
     *   - Автоматически вызывает token(), гарантируя наличие токена
     *   - Использует name="csrf_token" — стандартное именование
     *   - Скрытое поле (hidden) не видно пользователю, но отправляется с формой
     *   - Удобство: достаточно вызвать <?= Csrf::field() ?> в любой форме
     */
    public static function field(): string {
        return '<input type="hidden" name="csrf_token" value="' . self::token() . '">';
    }
}
?>