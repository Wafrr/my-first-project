// 45) Дан массив из подмассивов. Отсортируйте элементы в каждом подмассиве.
// 46) Дан двумерный массив [[1,2,3],[4,5,6],[7,8,9]]. Найдите сумму элементов.

$var1 = [
    [2, 1, 4, 3, 5],
    [3, 5, 2, 4, 1],
    [4, 3, 1, 5, 2],
];

foreach ($var1 as &$var2) {
    sort($var2);
}
unset($var2);

echo "45) Отсортированные подмассивы:<br>";
print_r($var1);
echo "<br>";

$var3 = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9],
];

$var4 = 0;
foreach ($var3 as $var2) {
    foreach ($var2 as $var5) {
        $var4 += $var5;
    }
}
echo "46) Сумма элементов: $var4<br>";
