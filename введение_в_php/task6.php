    $var1 += $var2;
}
echo "16) Сумма 1..100 = $var1<br>";

echo "17) Четные 1..100:<br>";
for ($var2 = 2; $var2 <= 100; $var2 += 2) {
    echo "$var2<br>";
}

echo "18) Все числа 1..100:<br>";
for ($var2 = 1; $var2 <= 100; $var2++) {
    echo "$var2<br>";
}

$var3 = 0;
for ($var2 = 1; $var2 <= 100; $var2++) {
    if ($var2 % 7 === 0) {
        $var3 += $var2;
    }
}
